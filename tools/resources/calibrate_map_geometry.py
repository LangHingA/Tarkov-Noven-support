"""Offline image/world calibration. Numerical evidence is not publication authority.

SVG observations must be measured in the original viewBox, not generated by
projecting world markers. No network, package writes or production state access.
"""
import argparse
import hashlib
import html
import json
import math
import re
from pathlib import Path

from investigate_lab_coordinates import MODELS, apply, errors, fit

LIMIT = 1024 * 1024
POLICY = dict(minFit=3, minHoldout=3, maxPickingUncertainty=0.25,
              maxHoldoutRmse=0.5, maxHoldoutError=1.0)
METHODS = ('visible-manual-survey', 'independent-public-survey')


def numbers(value, count):
    if not isinstance(value, list) or len(value) != count or any(
            type(x) not in (int, float) or not math.isfinite(x) or abs(x) > 1e7 for x in value):
        raise ValueError('invalid finite coordinates')
    return value


def inverse(t):
    a, b, c, d, tx, ty = t
    det = a*d-b*c
    if abs(det) < 1e-12:
        raise ValueError('singular projection')
    return d/det, -b/det, -c/det, a/det, (b*ty-d*tx)/det, (c*tx-a*ty)/det


def compose(outer, inner):
    a, b, c, d, tx, ty = outer
    e, f, g, h, ux, uy = inner
    return a*e+b*g, a*f+b*h, c*e+d*g, c*f+d*h, a*ux+b*uy+tx, c*ux+d*uy+ty


def projection(bounds, rotation, view):
    """World x/z -> SVG u/v, using the unchanged generator projection convention."""
    minx, minz, maxx, maxz = numbers(bounds, 4)
    vx, vy, width, height = numbers(view, 4)
    if minx >= maxx or minz >= maxz or min(width, height) <= 0:
        raise ValueError('invalid bounds/viewBox')
    angle = math.radians(numbers([rotation], 1)[0])
    cosine, sine = math.cos(angle), math.sin(angle)
    spanx, spanz = maxx-minx, maxz-minz
    # 旋转后使用四角包围盒；避免把画布尺寸当世界坐标比例。
    # Normalize by the rotated corner bounds, not an assumed canvas/world scale.
    rx = abs(cosine)*spanx + abs(sine)*spanz
    rz = abs(sine)*spanx + abs(cosine)*spanz
    a, b, c, d = width*cosine/rx, -width*sine/rx, -height*sine/rz, -height*cosine/rz
    mx, mz = (minx+maxx)/2, (minz+maxz)/2
    return a, b, c, d, vx+width/2-a*mx-b*mz, vy+height/2-c*mx-d*mz


def spread(points):
    if len(points) < 3:
        return dict(noncollinear=False, span=None, covarianceRatio=None)
    xs, ys = zip(*points)
    mx, my = sum(xs)/len(xs), sum(ys)/len(ys)
    xx = sum((x-mx)**2 for x in xs)
    yy = sum((y-my)**2 for y in ys)
    xy = sum((x-mx)*(y-my) for x, y in points)
    ratio = (xx*yy-xy*xy)/(xx+yy)**2 if xx+yy else 0
    return dict(noncollinear=ratio > 1e-8, span=[max(xs)-min(xs), max(ys)-min(ys)], covarianceRatio=ratio)


def validate(document):
    if type(document.get('schemaVersion')) is not int or document['schemaVersion'] != 1 or 'thresholds' in document:
        raise ValueError('unsupported schema or attempted policy override')
    if not re.fullmatch('[0-9a-f]{24}', document['mapId']):
        raise ValueError('invalid stable map ID')
    sources = document['sources']
    if not isinstance(sources, dict) or not 1 <= len(sources) <= 128:
        raise ValueError('source bound')
    for source in sources.values():
        if any(not isinstance(source.get(k), str) or not 0 < len(source[k]) <= 2048
               for k in ('uri', 'revision', 'sha256', 'lineage')) or not re.fullmatch('[0-9a-f]{64}', source['sha256']):
            raise ValueError('source needs pinned identity and lineage')
    floors = document['floors']
    if not isinstance(floors, list) or not 1 <= len(floors) <= 32:
        raise ValueError('floor bound')
    seen = set()
    for floor in floors:
        if not re.fullmatch('[A-Za-z0-9_-]{1,64}', floor['floorId']) or floor['floorId'] in seen:
            raise ValueError('invalid/duplicate floor')
        seen.add(floor['floorId'])
        sources[floor['imageSource']]
        if 'calibrationSource' in floor and floor['calibrationSource'] not in sources:
            raise ValueError('unknown calibration source')
        projection(floor['sourceBounds'], floor['rotation'], floor['viewBox'])
        points = floor['points']
        if not isinstance(points, list) or len(points) > 256:
            raise ValueError('point bound')
        identities, features, image_locations, world_locations = set(), set(), set(), set()
        for point in points:
            if any(not isinstance(point.get(k), str) or not 0 < len(point[k]) <= 512
                   for k in ('id', 'feature', 'region', 'imageLocator')):
                raise ValueError('point identity/semantic locator missing')
            uv = tuple(numbers(point['image'], 2))
            if point['role'] not in ('fit', 'holdout') or point['id'] in identities or point['feature'] in features or uv in image_locations:
                raise ValueError('duplicate observation or invalid split')
            identities.add(point['id']); features.add(point['feature']); image_locations.add(uv)
            vx, vy, width, height = floor['viewBox']
            if not (vx <= uv[0] <= vx+width and vy <= uv[1] <= vy+height):
                raise ValueError('point outside original viewBox')
            if point.get('world') is not None:
                world = tuple(numbers(point['world'], 2))
                if world in world_locations:
                    raise ValueError('reused world observation')
                world_locations.add(world)


def evidence_issue(point, image, sources, calibration=None):
    if point.get('world') is None:
        return 'UNKNOWN: matching independent world observation missing'
    evidence = point.get('worldEvidence', {})
    if not isinstance(evidence, dict):
        return 'UNKNOWN: independent world evidence missing'
    source = sources.get(evidence.get('source'))
    related = [image] + ([calibration] if calibration else [])
    if source is None or any(source['lineage'] == other['lineage'] or source['sha256'] == other['sha256'] for other in related):
        return 'UNKNOWN: source independence not established'
    if evidence.get('method') not in METHODS or evidence.get('samePhysicalFeatureReviewed') is not True:
        return 'UNKNOWN: physical feature or observation method not reviewed'
    if any(not isinstance(evidence.get(k), str) or not 0 < len(evidence[k]) <= 512
           for k in ('locator', 'gameVersion', 'reviewRecord')):
        return 'UNKNOWN: world locator/game version/independence review missing'
    uncertainty = evidence.get('pickingUncertaintyWorld')
    if type(uncertainty) not in (float, int) or not math.isfinite(uncertainty) or not 0 <= uncertainty <= POLICY['maxPickingUncertainty']:
        return 'UNKNOWN: picking uncertainty missing or exceeds fixed limit'
    return None


def calibrate(document):
    validate(document)
    result = dict(schemaVersion=1, mapId=document['mapId'], policy=POLICY.copy(),
                  evidenceBoundary='Source hashes and independence reviews are declarations requiring separate human verification; numerical success alone never authorizes publication.',
                  publicationAuthorized=False, sources=document['sources'], floors=[])
    for floor in document['floors']:
        baseline = inverse(projection(floor['sourceBounds'], floor['rotation'], floor['viewBox']))
        item = dict(floorId=floor['floorId'], baselineImageToWorld=list(baseline),
                    imageSource=floor['imageSource'], calibrationSource=floor.get('calibrationSource'),
                    status='UNKNOWN', acceptedFit=0, acceptedHoldout=0, observations=[], models={})
        accepted = []
        for point in floor['points']:
            issue = evidence_issue(point, document['sources'][floor['imageSource']], document['sources'],
                                   document['sources'].get(floor.get('calibrationSource')))
            item['observations'].append(dict(id=point['id'], role=point['role'], image=point['image'], world=point.get('world'),
                                              feature=point['feature'], region=point['region'], imageLocator=point['imageLocator'],
                                              worldEvidence=point.get('worldEvidence'), issue=issue))
            if issue is None:
                accepted.append(point)
        groups = {role: [p for p in accepted if p['role'] == role] for role in ('fit', 'holdout')}
        item['acceptedFit'], item['acceptedHoldout'] = len(groups['fit']), len(groups['holdout'])
        item['distribution'] = {role: dict(image=spread([p['image'] for p in ps]), world=spread([p['world'] for p in ps]),
                                          regions=len({p['region'] for p in ps})) for role, ps in groups.items()}
        ready = all(len(ps) >= 3 and item['distribution'][role]['image']['noncollinear'] and
                    item['distribution'][role]['world']['noncollinear'] and item['distribution'][role]['regions'] >= 2
                    for role, ps in groups.items())
        if ready:
            pairs = {role: [(apply(baseline, p['image']), p['world']) for p in ps] for role, ps in groups.items()}
            for model in MODELS:
                try:
                    correction = fit(pairs['fit'], model)
                    transform = compose(correction, baseline)
                    metric = errors(correction, pairs['holdout'])
                    residuals = []
                    for point in accepted:
                        predicted = apply(transform, point['image'])
                        residuals.append(dict(id=point['id'], role=point['role'], predicted=list(predicted),
                                              delta=[predicted[i]-point['world'][i] for i in (0, 1)],
                                              error=math.dist(predicted, point['world'])))
                    item['models'][model] = dict(imageToWorld=list(transform), training=errors(correction, pairs['fit']),
                                                 heldOut=metric, residuals=residuals,
                                                 numericPass=metric['rmse'] <= .5 and metric['maximum'] <= 1.)
                except ValueError as exc:
                    item['models'][model] = dict(error=str(exc), numericPass=False)
            item['status'] = 'NUMERIC_CRITERIA_MET_REVIEW_REQUIRED' if any(m['numericPass'] for m in item['models'].values()) else 'NUMERIC_FAIL'
        else:
            item['heldOut'] = dict(rmse='UNKNOWN', maximum='UNKNOWN')
        result['floors'].append(item)
    return result


def markdown(report):
    lines = ['# Image/world calibration evidence', '', report['evidenceBoundary'], '',
             'Policy: >=3 fit + >=3 independent holdout points per floor; uncertainty <=0.25; holdout RMSE <=0.5; max <=1.0 world units.', '',
             '| Floor | Fit / holdout | Result |', '| --- | --- | --- |']
    for floor in report['floors']:
        lines.append(f'| {floor["floorId"]} | {floor["acceptedFit"]} / {floor["acceptedHoldout"]} | {floor["status"]} |')
        for model, metrics in floor['models'].items():
            if 'heldOut' in metrics:
                lines.append(f'\n{floor["floorId"]} {model}: held-out RMSE {metrics["heldOut"]["rmse"]:.9g}, max {metrics["heldOut"]["maximum"]:.9g}.')
    return '\n'.join(lines)+'\n'


def residual_svg(report):
    # 只画残差，不嵌入第三方图像；没有控制点时明确显示 UNKNOWN。
    # Plot residuals without embedding third-party images; absent observations stay UNKNOWN.
    columns = max((len(m.get('residuals', [])) for f in report['floors'] for m in f['models'].values()), default=0)
    body = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d">' % (max(900, 160+columns*28), 180*len(report['floors'])),
            '<rect width="100%" height="100%" fill="white"/>']
    for index, floor in enumerate(report['floors']):
        y = 180*index
        body.append(f'<text x="10" y="{y+20}" font-size="14">{html.escape(floor["floorId"])}: {html.escape(floor["status"])}</text>')
        for row, (model, metrics) in enumerate(floor['models'].items()):
            body.append(f'<text x="10" y="{y+42+row*18}" font-size="12">{model}</text>')
            for column, point in enumerate(metrics.get('residuals', [])):
                x0, y0 = 130+column*28, y+42+row*18
                dx, dy = point['delta']
                color = 'blue' if point['role'] == 'fit' else 'red'
                body.append(f'<circle cx="{x0}" cy="{y0}" r="1" fill="{color}"/><line x1="{x0}" y1="{y0}" x2="{x0+max(-10,min(10,dx*10)):.4f}" y2="{y0+max(-8,min(8,dy*10)):.4f}" stroke="{color}"><title>{html.escape(model+" "+point["id"])} error={point["error"]:.9g}; arrows capped, 10px/unit</title></line>')
    return '\n'.join(body+['</svg>'])


def read_document(path):
    if path.stat().st_size > LIMIT:
        raise ValueError('input bound')
    def unique(pairs):
        output = {}
        for key, value in pairs:
            if key in output:
                raise ValueError('duplicate JSON key')
            output[key] = value
        return output
    return json.loads(path.read_bytes(), object_pairs_hook=unique)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True, help='New local report directory; never overwritten')
    args = parser.parse_args()
    document = read_document(args.input)
    report = calibrate(document)
    report['inputSha256'] = hashlib.sha256(args.input.read_bytes()).hexdigest()
    args.output.mkdir(parents=True, exist_ok=False)
    (args.output/'report.json').write_text(json.dumps(report, sort_keys=True, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    (args.output/'report.md').write_text(markdown(report), encoding='utf-8')
    (args.output/'residuals.svg').write_text(residual_svg(report), encoding='utf-8')


if __name__ == '__main__':
    main()
